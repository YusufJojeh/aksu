// Regenerates src/lib/database.types.ts from the live schema (read-only introspection).
// Usage: node scripts/gen-db-types.mjs [--check]
// Needs Docker running and POSTGRES_URL (or DATABASE_URL) in the env or .env.local.
// --check exits 1 if the committed file is out of date, for CI drift detection.
import { execSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'

const OUT = 'src/lib/database.types.ts'

function envFromFile(name) {
  if (!existsSync('.env.local')) return undefined
  const line = readFileSync('.env.local', 'utf8').split(/\r?\n/).find((l) => l.startsWith(`${name}=`))
  return line?.slice(name.length + 1).replace(/^"|"$/g, '')
}

// The transaction pooler (6543) is reachable from networks that block 5432; its Vercel URL carries a
// `supa=` marker that libpq clients reject, so drop it.
const rawUrl = process.env.DATABASE_URL ?? process.env.POSTGRES_URL ?? envFromFile('POSTGRES_URL')
const dbUrl = rawUrl?.replace(/[?&]supa=[^&]*/, '')
if (!dbUrl) {
  console.error('Set DATABASE_URL or POSTGRES_URL (vercel env pull .env.local).')
  process.exit(1)
}

// npx is a .cmd shim on Windows, so it needs a shell. The URL (with its secret and `&`s) goes through
// the environment and is expanded by the shell inside quotes, never concatenated into the command.
const urlRef = process.platform === 'win32' ? '"%GEN_TYPES_DB_URL%"' : '"$GEN_TYPES_DB_URL"'
const generated = execSync(`npx --yes supabase@2.117.0 gen types typescript --schema public --db-url ${urlRef}`, {
  encoding: 'utf8',
  env: { ...process.env, GEN_TYPES_DB_URL: dbUrl },
  stdio: ['ignore', 'pipe', 'inherit'],
})
const content = `// Generated by scripts/gen-db-types.mjs. Do not edit; rerun after every migration.\n${generated.replace(/\r\n/g, '\n').trimEnd()}\n`

if (process.argv.includes('--check')) {
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : ''
  if (current !== content) {
    console.error(`${OUT} is out of date. Run: node scripts/gen-db-types.mjs`)
    process.exit(1)
  }
  console.log(`${OUT} is up to date.`)
} else {
  writeFileSync(OUT, content)
  console.log(`Wrote ${OUT}`)
}
